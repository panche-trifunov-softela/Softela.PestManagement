CREATE TABLE service_addresses (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id INT NOT NULL,
    customer_id INT NOT NULL,
    service_address_name VARCHAR(255) NOT NULL,
    service_address_type VARCHAR(50),
    address VARCHAR(500),
    city VARCHAR(255),
    state VARCHAR(50),
    zip VARCHAR(20),
    contact_name VARCHAR(255),
    contact_phone VARCHAR(50),
    contact_email VARCHAR(255),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL,
    modified_at TIMESTAMPTZ NOT NULL,
    created_by UUID NOT NULL,
    modified_by UUID NOT NULL,
    CONSTRAINT fk_service_addresses_tenants FOREIGN KEY (tenant_id) REFERENCES tenants(id),
    CONSTRAINT fk_service_addresses_customers FOREIGN KEY (customer_id) REFERENCES customers(id)
);
