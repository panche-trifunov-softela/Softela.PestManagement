CREATE TABLE programs (
    id                  INT          GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id           INT          NOT NULL,
    estimate_id         INT          NOT NULL,
    name                VARCHAR(255) NOT NULL,
    status              BOOLEAN      NOT NULL DEFAULT FALSE,
    notes               TEXT,
    start_date          TIMESTAMPTZ  NOT NULL,
    end_date            TIMESTAMPTZ,
    renewal_date        TIMESTAMPTZ,
    canceled_date       TIMESTAMPTZ,
    pending_cancel_date TIMESTAMPTZ,
    frequency           SMALLINT     NOT NULL,
    is_deleted          BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at          TIMESTAMPTZ  NOT NULL,
    modified_at         TIMESTAMPTZ  NOT NULL,
    created_by          UUID         NOT NULL,
    modified_by         UUID         NOT NULL,
    CONSTRAINT fk_programs_tenants   FOREIGN KEY (tenant_id)   REFERENCES tenants(id),
    CONSTRAINT fk_programs_estimates FOREIGN KEY (estimate_id) REFERENCES estimates(id)
);
